<?php

namespace App\Agent\Runtime;

use App\Support\ArabicTextNormalizer;

class CurrentBusinessPolicy
{
    public function reply(string $text): ?string
    {
        $text = ArabicTextNormalizer::normalize($text);
        if (str_contains($text,'جواب') && preg_match('/رسوم|مصاريف|فلوس|بكام/u',$text)) {
            return 'مفيش رسوم على الجواب عندنا. المصاريف الإدارية الخاصة بالتقسيط منفصلة، وبتتحسب حسب الموديل والنظام والمدة.';
        }
        if (preg_match('/طالب.*(?:بطاقه|بطاقتي)|(?:بطاقه|بطاقتي).*طالب/u',$text) && ! preg_match('/مش بشتغل|لا اعمل/u',$text)) {
            return 'كلمة طالب في البطاقة لوحدها مش سبب للرفض. المهم سنك وشغلك الحالي؛ حضرتك بتشتغل إيه حاليًا؟';
        }
        if (! preg_match('/مش (?:محامي|ضابط|ظابط|امين)|كنت (?:محامي|ضابط|ظابط)/u', $text)) {
            if (preg_match('/جيش|قوات مسلحه/u', $text) && preg_match('/ضابط|ظابط|نقيب|رائد|مقدم|عقيد|عميد|لواء|ملازم/u', $text)) {
                return 'ضباط الجيش متاح لهم التقديم بكشف حساب بنكي عن آخر ٦ شهور، والطلب بيخضع لباقي الشروط والمراجعة. كشف الحساب موجود؟';
            }
            if (preg_match('/شرطه/u', $text) && preg_match('/ضابط|ظابط|امين|نقيب|رائد|مقدم|عقيد|عميد|لواء|ملازم/u', $text)) {
                return 'للأسف ضباط الشرطة بكل الرتب وأمناء الشرطة مش متاح لهم التقديم للتقسيط لأن جهات التمويل لا تتعامل مع المهن دي. الشراء كاش متاح.';
            }
            if (preg_match('/(?:انا|شغال|وظيفتي|خالي|والدي|اخويا)\s+(?:ضابط|ظابط|نقيب|رائد|عقيد|عميد|لواء|ملازم)(?:\s|$)/u', $text)
                && ! preg_match('/جيش|شرطه|قوات مسلحه/u', $text)) {
                return 'حضرتك ضابط جيش ولا شرطة؟';
            }
        }
        if (preg_match('/مايلو|mylo|milo|فاليو|valu/iu', $text)) {
            return 'حاليًا بنسحب ليمت أمان بس، ومش شغالين مع مايلو أو جهات تانية. ليمت جهة تانية مش متاح تدفع بيه المقدم عندنا.';
        }
        if (preg_match('/تحت (?:ال)?تدريب|تحت تمرين|تحت (?:ال)?اختبار|(?:بقاله|بقالي|بقالها)\s*(?:3|ثلاث|تلات|ثلاثه|تلاته)\s*ايام/u', $text)) {
            return 'الشغل من ٣ أيام أو تحت التدريب لسه مش مستوفي شرط مدة العمل. لازم يعدي على التعيين من ٣ لـ٦ شهور حسب الحالة؛ البطاقة لوحدها مش كفاية لاعتماد شغل جديد.';
        }
        if (preg_match('/(?:انا|شغال|بشتغل|وظيفتي|مهنتي|خالي|والدي|اخويا|اخي)\s+(?:شغال\s+)?محامي/u', $text)
            && ! preg_match('/مش محامي|مش شغال محامي|كنت محامي/u', $text)) {
            return 'للأسف مهنة المحاماة مش متاح لها التقديم للتقسيط لأن جهات التمويل لا تتعامل مع المهنة دي. الشراء كاش متاح.';
        }
        if (preg_match('/(?:انا|شغال|وظيفتي|مهنتي|خالي|والدي|اخويا)\s+(?:شغال\s+)?(?:قاضي|وكيل نيابه)/u', $text)
            && ! preg_match('/مش قاضي|كنت قاضي|مش وكيل|كنت وكيل/u',$text)) {
            return 'للأسف القضاة ووكلاء النيابة مش متاح لهم التقديم للتقسيط لأن جهات التمويل لا تتعامل مع المهن دي. الشراء كاش متاح.';
        }
        return null;
    }
}
