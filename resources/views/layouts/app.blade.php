<script>
document.addEventListener('DOMContentLoaded', () => {
    const brandSelect = document.getElementById('calc_brandSelect');
    const machineSelect = document.getElementById('calc_machineSelect');
    const systemSelect = document.getElementById('calc_systemSelect');
    const monthsSelect = document.getElementById('calc_monthsSelect');
    const downInput = document.getElementById('calc_downPayment');
    const form = document.getElementById('calcForm');

    if (!form) return;

    // ✅ فلترة المكن حسب الماركة
    brandSelect?.addEventListener('change', () => {
        const brandId = brandSelect.value;
        machineSelect.disabled = !brandId;
        machineSelect.value = "";

        [...machineSelect.options].forEach(opt => {
            if (!opt.value) return;
            opt.style.display = (opt.dataset.brand == brandId) ? 'block' : 'none';
        });
    });

    // ✅ عرض الشهور حسب النظام
    systemSelect?.addEventListener('change', () => {
        const selected = systemSelect.options[systemSelect.selectedIndex];
        const plans = selected.dataset.plans ? JSON.parse(selected.dataset.plans) : [];
        const adminFees = parseFloat(selected.dataset.fees || 0);

        systemSelect.dataset.adminFees = adminFees;

        monthsSelect.innerHTML = `<option value="">اختر...</option>`;

        if (plans.length) {
            monthsSelect.disabled = false;

            plans.forEach(p => {
                const opt = document.createElement('option');
                opt.value = p.months;
                opt.textContent = `${p.months} شهر (${p.interest}% فايدة)`;
                opt.dataset.interest = p.interest;
                monthsSelect.appendChild(opt);
            });

        } else {
            monthsSelect.disabled = true;
        }
    });

    // ✅ حساب القسط بكل الأنظمة
    form.addEventListener('submit', e => {
        e.preventDefault();

        const machineOption = machineSelect.options[machineSelect.selectedIndex];
        const monthsOption = monthsSelect.options[monthsSelect.selectedIndex];
        const selectedSystem = systemSelect.options[systemSelect.selectedIndex];

        if (!brandSelect.value || !machineSelect.value || !systemSelect.value || !monthsSelect.value) {
            Swal.fire('خطأ', 'من فضلك اختر جميع الحقول المطلوبة', 'error');
            return;
        }

        const installmentPrice = parseFloat(machineOption?.dataset.price || 0);  
        const cashPrice = parseFloat(machineOption?.dataset.cash || installmentPrice); 
        const downPayment = parseFloat(downInput?.value || 0);
        const interest = parseFloat(monthsOption?.dataset.interest || 0);
        const months = parseInt(monthsOption?.value || 0);
        const adminFeesPercent = parseFloat(selectedSystem?.dataset.fees || 0);
        const systemName = selectedSystem.textContent.trim();

        if (!installmentPrice || !months) {
            Swal.fire('⚠️', 'تأكد إنك اخترت المكنة وعدد الشهور بشكل صحيح', 'warning');
            return;
        }

        // ❌ تحقق من أن المقدم مش أكبر من سعر الكاش
        if (downPayment >= cashPrice) {
            Swal.fire('⚠️', 'الدفعة الأولى لا يمكن أن تكون أكبر من أو تساوي سعر المكنة الكاش', 'warning');
            return;
        }

        let monthly = 0;
        let totalWithInterest = 0;
        let adminFeesAmount = 0;

        // 🟦 ⭐ نظام أمان زيرو مصاريف
        if (systemName.includes("زيرو مصاريف")) {

            const remaining = cashPrice - downPayment;
            const plus75 = remaining * 1.075; // +7.5%

            totalWithInterest = plus75 * (1 + interest / 100);  
            monthly = totalWithInterest / months;
            adminFeesAmount = 0; // مفيش مصاريف إدارية

        } else {

            // 🟩 ⭐ المعادلة الأصلية
            const remaining = installmentPrice - downPayment;
            totalWithInterest = remaining + (remaining * interest / 100);
            monthly = totalWithInterest / months;
            adminFeesAmount = remaining * (adminFeesPercent / 100);
        }

        Swal.fire({
            title: '📅 تفاصيل القسط',
            html: `
                <p>قيمة الفايدة: <b>${interest}%</b></p>
                <p>إجمالي بعد الفايدة: <b>${totalWithInterest.toLocaleString()} جنيه</b></p>
                <p>المصاريف الإدارية: <b>${adminFeesAmount.toLocaleString()} جنيه</b></p>
                <hr>
                <h3>القسط الشهري: <b style="color:#00bcd4">${Math.round(monthly).toLocaleString()} جنيه</b></h3>
                <small style="color:gray;">*المصاريف الادارية بتدفع مرة واحدة وانت بتستلم المكنه</small>
            `,
            icon: 'success',
            confirmButtonText: 'تمام',
            confirmButtonColor: '#00bcd4'
        });
    });
});
